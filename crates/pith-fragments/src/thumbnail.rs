//! Кадр для предпросмотра при перемотке.
//!
//! Пока пользователь тянет ползунок, полезно видеть, что там происходит.
//! Кадр достаёт `ffmpeg` — отдельно от воспроизведения, поэтому картинка
//! в окне при этом не дёргается.

use std::path::Path;

/// Ширина миниатюры, точки. Высота считается по пропорциям кадра.
///
/// Согласована с окном предпросмотра: оно этой же ширины, и большего
/// кадра всё равно не покажет.
const WIDTH: u32 = 160;

/// Достаёт один кадр в указанной секунде.
///
/// Возвращает изображение в формате PNG. `None` означает, что `ffmpeg`
/// недоступен или кадра в этом месте нет.
pub fn grab_frame(video: &Path, position: f64) -> Option<Vec<u8>> {
    let output = crate::quiet::command("ffmpeg")
        .args(["-v", "error"])
        // Декодируем только опорные кадры. Для подсказки этого довольно,
        // а на 4К HEVC вдвое быстрее: 220 мс против 400 на замере.
        // Аппаратное декодирование не помогает — его настройка ради
        // одного кадра стоит дороже самой работы.
        .args(["-skip_frame", "nokey"])
        // Перемотка до `-i` и без точного позиционирования: ждать
        // декодирования до нужной миллисекунды здесь незачем.
        .args(["-ss", &crate::command::format_time(position.max(0.0))])
        .arg("-noaccurate_seek")
        .arg("-i")
        .arg(video)
        // Ни звука, ни субтитров, ни данных: нужен один кадр.
        .args(["-an", "-sn", "-dn"])
        .args(["-frames:v", "1"])
        .args(["-vf", &format!("scale={WIDTH}:-2")])
        // Быстрое сжатие: картинка живёт доли секунды, размер не важен.
        .args(["-compression_level", "1"])
        // Один кадр в поток вывода, без временного файла.
        .args(["-f", "image2", "-c:v", "png", "-"])
        .output()
        .ok()?;

    if !output.status.success() || output.stdout.is_empty() {
        return None;
    }

    Some(output.stdout)
}
