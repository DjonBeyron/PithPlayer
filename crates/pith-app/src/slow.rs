//! Поиск того, что подвешивает картинку.
//!
//! Кадр при 60 к/с длится 16,7 мс. Всё, что делается в потоке интерфейса
//! дольше, видно глазом как рывок или заминка: запись файла, запуск
//! внешнего процесса, обращение к реестру.
//!
//! Обёртка `probe` замеряет операцию и пишет в журнал, если та не уложилась
//! в бюджет кадра. В обычной работе она молчит и ничего не стоит.

use std::time::Instant;

/// Сколько может занять операция, прежде чем её стоит заметить.
///
/// Чуть больше кадра при 60 к/с: разовые 17–20 мс глазом не видны,
/// а вот всё, что дольше, уже сбивает плавность.
const BUDGET_MS: u128 = 20;

/// Замеряет операцию и жалуется в журнал, если она задержала кадр.
pub fn probe<T>(name: &'static str, action: impl FnOnce() -> T) -> T {
    let started = Instant::now();
    let result = action();
    let elapsed = started.elapsed();

    if elapsed.as_millis() >= BUDGET_MS {
        tracing::warn!(
            операция = name,
            ms = elapsed.as_millis(),
            "задержала кадр интерфейса"
        );
    } else {
        tracing::trace!(операция = name, мкс = elapsed.as_micros(), "выполнено");
    }

    result
}

/// Замер целого кадра: сообщает о заминках, не привязанных к конкретной
/// операции, — например об отрисовке слишком длинного списка.
pub struct FrameProbe {
    started: Instant,
}

impl FrameProbe {
    pub fn start() -> Self {
        Self {
            started: Instant::now(),
        }
    }

    /// Завершает замер. `hint` описывает, что было на экране, — по нему
    /// в журнале видно, какой кадр оказался долгим.
    pub fn finish(self, hint: &str) {
        let elapsed = self.started.elapsed();

        // Порог кадра выше: сюда попадает и работа mpv по отрисовке видео,
        // и разовые скачки при смене файла. Втрое против бюджета — это
        // уже заметная глазом заминка, и молчать о ней нельзя: прежний
        // порог в пять бюджетов пропускал те, на которые жаловались.
        if elapsed.as_millis() >= BUDGET_MS * 3 {
            tracing::warn!(
                ms = elapsed.as_millis(),
                состояние = hint,
                "долгий кадр интерфейса"
            );
        }
    }
}
