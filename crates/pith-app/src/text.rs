//! Чистка текста реплик: из субтитров он попадает и в буфер обмена,
//! и в названия закладок, а оттуда — в имена вырезанных файлов.

/// Все виды тире, с которых начинают реплику в субтитрах.
///
/// Их пишут кто во что горазд: дефис, минус, короткое и длинное тире,
/// неразрывный дефис. Знать разницу пользователю незачем — убираем все.
const DASHES: &[char] = &[
    '-',        // U+002D дефис-минус
    '\u{2010}', // дефис
    '\u{2011}', // неразрывный дефис
    '\u{2012}', // цифровое тире
    '\u{2013}', // короткое тире
    '\u{2014}', // длинное тире
    '\u{2015}', // горизонтальная черта
    '\u{2212}', // минус
    '\u{FE58}', // малое длинное тире
    '\u{FF0D}', // широкий дефис
];

/// Убирает тире в начале строк.
///
/// В субтитрах с тире начинается каждая реплика диалога, и в заметках
/// оно оказывается мусором: скопировали фразу, а её приходится править
/// руками. Убираем только в начале строки — тире посреди предложения
/// это знак препинания («Москва — столица»), и трогать его нельзя.
pub fn strip_leading_dashes(text: &str) -> String {
    let cleaned: Vec<&str> = text.lines().map(strip_line).collect();

    cleaned.join("\n")
}

/// Сводит реплику в одну строку — такой она годится в название закладки.
///
/// Реплика бывает многострочной, а название — нет; тире каждой строки
/// диалога при склейке оказалось бы посреди названия, а название идёт
/// в имя вырезанного файла. Пустая после чистки строка названием
/// не становится: закладка подпишется словом по умолчанию.
pub fn to_single_line(text: &str) -> Option<String> {
    let parts: Vec<&str> = text
        .lines()
        .map(strip_line)
        .filter(|line| !line.is_empty())
        .collect();

    let name = parts.join(" ");
    (!name.is_empty()).then_some(name)
}

/// Одна строка без тире в начале и без крайних пробелов.
fn strip_line(line: &str) -> &str {
    line.trim_start().trim_start_matches(DASHES).trim()
}

#[cfg(test)]
mod tests {
    use super::{strip_leading_dashes, to_single_line};

    #[test]
    fn убирает_дефис_в_начале() {
        assert_eq!(strip_leading_dashes("- Привет"), "Привет");
        assert_eq!(strip_leading_dashes("-Привет"), "Привет");
    }

    #[test]
    fn убирает_длинное_и_короткое_тире() {
        assert_eq!(strip_leading_dashes("— Привет"), "Привет");
        assert_eq!(strip_leading_dashes("– Привет"), "Привет");
        assert_eq!(strip_leading_dashes("−Привет"), "Привет");
    }

    #[test]
    fn убирает_тире_в_каждой_строке_диалога() {
        let text = "- Ты идёшь?\n— Нет.";
        assert_eq!(strip_leading_dashes(text), "Ты идёшь?\nНет.");
    }

    #[test]
    fn не_трогает_тире_внутри_предложения() {
        let text = "Москва — столица, всё-таки.";
        assert_eq!(strip_leading_dashes(text), text);
    }

    #[test]
    fn убирает_тире_после_пробелов_и_повторы() {
        assert_eq!(strip_leading_dashes("   — Привет"), "Привет");
        assert_eq!(strip_leading_dashes("-- Привет"), "Привет");
    }

    #[test]
    fn строка_из_одних_тире_пустеет() {
        assert_eq!(strip_leading_dashes("---"), "");
    }

    #[test]
    fn текст_без_тире_не_меняется() {
        assert_eq!(strip_leading_dashes("Привет"), "Привет");
    }

    #[test]
    fn название_склеивается_в_одну_строку_без_тире() {
        // Ровно тот случай, на котором тире в названии и заметили.
        let text = "- Hi. Hi.\n- (sloshing)";
        assert_eq!(to_single_line(text).as_deref(), Some("Hi. Hi. (sloshing)"));
    }

    #[test]
    fn пустая_реплика_названием_не_становится() {
        assert_eq!(to_single_line("  \n-\n  "), None);
        assert_eq!(to_single_line(""), None);
    }

    #[test]
    fn пустые_строки_реплики_не_дают_лишних_пробелов() {
        assert_eq!(to_single_line("- Раз\n\n- Два").as_deref(), Some("Раз Два"));
    }
}
