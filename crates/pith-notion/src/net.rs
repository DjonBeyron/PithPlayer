//! Клиент для запросов к Notion.
//!
//! **Про прокси.** `ureq` сам подхватывает `HTTP_PROXY` и `HTTPS_PROXY`
//! из окружения, но плеер, запущенный из проводника, окружения
//! не наследует: программы, дающие доступ в сеть, прописывают прокси
//! в настройки системы. Читать их — дело приложения (это дело Windows),
//! оно один раз называет адрес через `use_proxy`.
//!
//! Notion у пользователя открывается и напрямую, так что без прокси всё
//! работает. Но если весь доступ в сеть идёт через него, идти должны
//! и наши запросы: иначе плеер ведёт себя не как остальные программы.

use std::sync::OnceLock;
use std::time::Duration;

/// Адрес прокси, названный приложением. Пусто — как решит `ureq`.
static PROXY: OnceLock<Option<String>> = OnceLock::new();

/// Называет прокси для всех запросов к Notion.
///
/// Вызывается один раз при запуске, до первого запроса.
pub fn use_proxy(uri: Option<String>) {
    if let Some(uri) = uri.as_deref() {
        tracing::info!(прокси = uri, "запросы к Notion пойдут через прокси");
    }

    if PROXY.set(uri).is_err() {
        tracing::debug!("прокси уже назначен, второй раз не меняем");
    }
}

/// Клиент, общий на все запросы.
///
/// Именно общий, а не новый на каждый запрос: у клиента свой пул
/// соединений, и заведённый заново он каждый раз заново открывает TCP
/// и пожимает руки по TLS. Через прокси это стоило больше секунды
/// на запрос — на выгрузке из тридцати строк почти минута на одни
/// рукопожатия. `ureq::Agent` дёшев в клонировании и пул делит с копиями.
static AGENT: OnceLock<ureq::Agent> = OnceLock::new();

/// Клиент с общими настройками.
///
/// Отказ разбираем сами: иначе клиент отдаёт один код состояния,
/// а объяснение Notion остаётся в теле ответа и пропадает.
pub(crate) fn agent(timeout: Duration) -> ureq::Agent {
    AGENT
        .get_or_init(|| {
            let mut config = ureq::Agent::config_builder()
                .timeout_global(Some(timeout))
                .http_status_as_error(false);

            // Только когда адрес назван: иначе не мешаем `ureq` взять
            // прокси из окружения самому.
            if let Some(proxy) = configured() {
                config = config.proxy(Some(proxy));
            }

            ureq::Agent::new_with_config(config.build())
        })
        .clone()
}

/// Прокси в виде, пригодном для клиента.
///
/// Негодный адрес не повод падать: запрос уйдёт напрямую, а о причине
/// скажет журнал.
fn configured() -> Option<ureq::Proxy> {
    let uri = PROXY.get()?.as_deref()?;

    match ureq::Proxy::new(uri) {
        Ok(proxy) => Some(proxy),
        Err(e) => {
            tracing::warn!(прокси = uri, error = %e, "адрес прокси не разобрать");
            None
        }
    }
}
