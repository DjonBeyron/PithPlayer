//! Клиент для запросов к базе — один на все три вида запросов.
//!
//! **Про прокси.** `ureq` сам подхватывает `HTTP_PROXY` и `HTTPS_PROXY`
//! из окружения, и этого достаточно, когда плеер запускают из консоли.
//! Но запущенный из проводника он окружения не наследует: программы,
//! которые дают доступ в сеть, прописывают прокси **в настройки системы**,
//! а не в переменные. Без него запрос уходит напрямую, а имя
//! `api.themoviedb.org` у части провайдеров разрешается в `127.0.0.1` —
//! и пользователь видит «connection refused», хотя сеть работает.
//!
//! Читать настройки системы — дело Windows и потому дело приложения:
//! крейт знает только про базу фильмов. Приложение один раз называет
//! адрес через `use_proxy`, и дальше все запросы идут через него.

use std::sync::OnceLock;
use std::time::Duration;

/// Адрес прокси, названный приложением. Пусто — как решит `ureq`.
static PROXY: OnceLock<Option<String>> = OnceLock::new();

/// Называет прокси для всех запросов к базе.
///
/// Вызывается один раз при запуске, до первого запроса. Второй вызов
/// ничего не меняет: менять транспорт на ходу незачем, а гонок с рабочими
/// потоками так заведомо нет.
pub fn use_proxy(uri: Option<String>) {
    if let Some(uri) = uri.as_deref() {
        tracing::info!(прокси = uri, "запросы к базе фильмов пойдут через прокси");
    }

    if PROXY.set(uri).is_err() {
        tracing::debug!("прокси уже назначен, второй раз не меняем");
    }
}

/// Клиент, общий на все запросы.
///
/// Именно общий, а не новый на каждый запрос: у клиента свой пул
/// соединений, и заведённый заново он каждый раз заново открывает TCP
/// и пожимает руки по TLS. Через прокси это стоит больше секунды
/// на запрос, а фотографий за раз тянется десяток. `ureq::Agent` дёшев
/// в клонировании и пул делит с копиями — потоки фотографий разбирают
/// один и тот же.
static AGENT: OnceLock<ureq::Agent> = OnceLock::new();

/// Клиент с общими настройками: срок ожидания и прокси.
pub(crate) fn agent(timeout: Duration) -> ureq::Agent {
    AGENT
        .get_or_init(|| {
            let mut config = ureq::Agent::config_builder().timeout_global(Some(timeout));

            // Только когда адрес назван: иначе не мешаем `ureq` взять
            // прокси из окружения самому.
            if let Some(proxy) = configured() {
                config = config.proxy(Some(proxy));
            }

            ureq::Agent::new_with_config(config.build())
        })
        .clone()
}

/// Прокси в виде, пригодном для клиента.
///
/// Негодный адрес не повод падать: запрос уйдёт напрямую, а о причине
/// скажет журнал.
fn configured() -> Option<ureq::Proxy> {
    let uri = PROXY.get()?.as_deref()?;

    match ureq::Proxy::new(uri) {
        Ok(proxy) => Some(proxy),
        Err(e) => {
            tracing::warn!(прокси = uri, error = %e, "адрес прокси не разобрать");
            None
        }
    }
}
